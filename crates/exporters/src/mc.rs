fn render_entry(entry: &McEntry, roles: &SemanticRoles, palette: &Base16Palette) -> String {
    let fg = resolve_color(entry.fg, roles, palette);
    let bg = resolve_color(entry.bg, roles, palette);
    if entry.attrs.is_empty() {
        format!("{fg};{bg}")
    } else {
        format!("{fg};{};{}", bg, entry.attrs.join("+"))
    }
}

fn resolve_color<'a>(
    mc_color: McColor,
    roles: &'a SemanticRoles,
    palette: &'a Base16Palette,
) -> &'a str {
    match mc_color {
        McColor::Role {
            roles: color_roles,
            fallback_base,
        } => {
            for role in color_roles {
                if let Some(color) = role_color(roles, *role) {
                    return color;
                }
            }
            color(palette, fallback_base)
        }
        McColor::FileKind(kind) => resolve_file_kind_color(kind, roles, palette),
    }
}

fn mc_preserved_items(roles: &SemanticRoles) -> Vec<PreservedItem> {
    let mut items = Vec::new();
    for section in mc_sections() {
        for entry in section.entries {
            push_source(&mut items, roles, section.name, entry.key, "fg", entry.fg);
            push_source(&mut items, roles, section.name, entry.key, "bg", entry.bg);
        }
    }
    items
}

fn push_source(
    items: &mut Vec<PreservedItem>,
    roles: &SemanticRoles,
    section: &str,
    key: &str,
    property: &str,
    mc_color: McColor,
) {
    let target = format!("{section}.{key}.{property}");
    match mc_color {
        McColor::Role {
            roles: color_roles, ..
        } => {
            for role in color_roles {
                if let Some(value) = roles.get(role) {
                    if let Some(source) = role_source(value) {
                        items.push(PreservedItem { target, source });
                        break;
                    }
                }
            }
        }
        McColor::FileKind(kind) => push_file_kind_source(items, roles, &target, kind),
    }
}

fn mc_dropped_items(theme: &ResolvedTheme) -> Vec<String> {
    let mut dropped = dropped_items(theme);
    dropped.push("Helix syntax scopes collapse to Midnight Commander UI fields".to_owned());
    dropped.push("Helix underline styles collapse to Midnight Commander underline".to_owned());
    dropped.push("Helix dim, crossed-out, and reversed modifiers are not represented".to_owned());
    dropped
}

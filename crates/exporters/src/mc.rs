pub fn export_mc_skin(
    theme: &ResolvedTheme,
    roles: &SemanticRoles,
    palette: &Base16Palette,
    warnings: Vec<Warning>,
) -> (String, ExportReport) {
    let mut output = String::new();
    output.push_str("[skin]\n");
    output.push_str(&format!(
        "    description = {} - generated by Helix Theme Transformer\n",
        theme.name
    ));
    output.push_str("    truecolors = true\n");
    output.push('\n');
    output.push_str("[Lines]\n");
    for (key, value) in mc_lines() {
        output.push_str(&format!("    {key} = {value}\n"));
    }

    for section in mc_sections() {
        output.push('\n');
        output.push_str(&format!("[{}]\n", section.name));
        for entry in section.entries {
            output.push_str(&format!(
                "    {} = {}\n",
                entry.key,
                render_entry(&entry, roles, palette)
            ));
        }
    }

    let report = ExportReport {
        exporter: "mc".to_owned(),
        source: theme.source_path.to_string(),
        preserved: mc_preserved_items(roles),
        dropped: mc_dropped_items(theme),
        warnings,
    };
    (output, report)
}

#[derive(Debug, Clone)]
struct McSection {
    name: &'static str,
    entries: Vec<McEntry>,
}

#[derive(Debug, Clone, Copy)]
struct McEntry {
    key: &'static str,
    fg: McColor,
    bg: McColor,
    attrs: &'static [&'static str],
}

#[derive(Debug, Clone, Copy)]
enum McColor {
    Role {
        roles: &'static [Role],
        fallback_base: &'static str,
    },
    FileKind(FileKind),
}

impl McColor {
    const fn new(roles: &'static [Role], fallback_base: &'static str) -> Self {
        Self::Role {
            roles,
            fallback_base,
        }
    }

    const fn file_kind(kind: FileKind) -> Self {
        Self::FileKind(kind)
    }
}


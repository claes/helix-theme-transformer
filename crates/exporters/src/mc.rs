#[derive(Debug)]
struct McFilehighlightGroup {
    section: &'static str,
    extensions: Vec<&'static str>,
}

fn mc_filehighlight_groups() -> Vec<McFilehighlightGroup> {
    let mut groups = vec![
        McFilehighlightGroup {
            section: "temp",
            extensions: Vec::new(),
        },
        McFilehighlightGroup {
            section: "archive",
            extensions: Vec::new(),
        },
        McFilehighlightGroup {
            section: "doc",
            extensions: Vec::new(),
        },
        McFilehighlightGroup {
            section: "source",
            extensions: Vec::new(),
        },
        McFilehighlightGroup {
            section: "media",
            extensions: Vec::new(),
        },
        McFilehighlightGroup {
            section: "graph",
            extensions: Vec::new(),
        },
        McFilehighlightGroup {
            section: "database",
            extensions: Vec::new(),
        },
    ];

    for group in file_extension_groups() {
        let Some(section) = mc_filehighlight_section(group.kind) else {
            continue;
        };
        if let Some(target) = groups.iter_mut().find(|target| target.section == section) {
            target.extensions.extend(group.extensions);
        }
    }

    groups
        .into_iter()
        .filter(|group| !group.extensions.is_empty())
        .collect()
}

fn mc_filehighlight_section(kind: FileKind) -> Option<&'static str> {
    match kind {
        FileKind::Archive => Some("archive"),
        FileKind::Document => Some("doc"),
        FileKind::Source => Some("source"),
        FileKind::Audio => Some("media"),
        FileKind::ImageVideo => Some("graph"),
        FileKind::Database => Some("database"),
        FileKind::Temporary => Some("temp"),
        _ => None,
    }
}

fn render_entry(entry: &McEntry, roles: &SemanticRoles, palette: &Base16Palette) -> String {
    let fg = resolve_color(entry.fg, roles, palette);
    let bg = resolve_color(entry.bg, roles, palette);
    if entry.attrs.is_empty() {
        format!("{fg};{bg}")
    } else {
        format!("{fg};{};{}", bg, entry.attrs.join("+"))
    }
}

fn resolve_color<'a>(
    mc_color: McColor,
    roles: &'a SemanticRoles,
    palette: &'a Base16Palette,
) -> &'a str {
    match mc_color {
        McColor::Role {
            roles: color_roles,
            fallback_base,
        } => {
            for role in color_roles {
                if let Some(color) = role_color(roles, *role) {
                    return color;
                }
            }
            color(palette, fallback_base)
        }
        McColor::FileKind(kind) => resolve_file_kind_color(kind, roles, palette),
    }
}

fn resolve_colortable_color(
    mc_color: McColor,
    roles: &SemanticRoles,
    palette: &Base16Palette,
) -> String {
    mc_256_color(resolve_color(mc_color, roles, palette))
}

fn mc_256_color(color: &str) -> String {
    let rgb = parse_rgb(color).expect("resolved exporter colors should be valid rgb hex colors");
    if rgb.r == rgb.g && rgb.g == rgb.b {
        return format!("gray{}", quantize(rgb.r, 23));
    }

    format!(
        "rgb{}{}{}",
        quantize(rgb.r, 5),
        quantize(rgb.g, 5),
        quantize(rgb.b, 5)
    )
}

fn quantize(component: u8, max: u8) -> u8 {
    ((component as u16 * max as u16 + 127) / 255) as u8
}

fn mc_preserved_items(roles: &SemanticRoles) -> Vec<PreservedItem> {
    let mut items = Vec::new();
    for section in mc_sections() {
        for entry in section.entries {
            push_source(&mut items, roles, section.name, entry.key, "fg", entry.fg);
            push_source(&mut items, roles, section.name, entry.key, "bg", entry.bg);
        }
    }
    items
}

fn push_source(
    items: &mut Vec<PreservedItem>,
    roles: &SemanticRoles,
    section: &str,
    key: &str,
    property: &str,
    mc_color: McColor,
) {
    let target = format!("{section}.{key}.{property}");
    match mc_color {
        McColor::Role {
            roles: color_roles, ..
        } => {
            for role in color_roles {
                if let Some(value) = roles.get(role) {
                    if let Some(source) = role_source(value) {
                        items.push(PreservedItem { target, source });
                        break;
                    }
                }
            }
        }
        McColor::FileKind(kind) => push_file_kind_source(items, roles, &target, kind),
    }
}

fn mc_dropped_items(theme: &ResolvedTheme) -> Vec<String> {
    let mut dropped = dropped_items(theme);
    dropped.push("Helix syntax scopes collapse to Midnight Commander UI fields".to_owned());
    dropped.push("Helix underline styles collapse to Midnight Commander underline".to_owned());
    dropped.push("Helix dim, crossed-out, and reversed modifiers are not represented".to_owned());
    dropped.push("MC_COLOR_TABLE quantizes truecolor values to MC 256-color tokens".to_owned());
    dropped
}

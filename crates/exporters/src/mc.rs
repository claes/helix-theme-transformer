pub fn export_mc_skin(
    theme: &ResolvedTheme,
    roles: &SemanticRoles,
    palette: &Base16Palette,
    warnings: Vec<Warning>,
) -> (String, ExportReport) {
    let export = export_mc(theme, roles, palette, warnings);
    (export.skin_ini, export.report)
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct McExport {
    pub skin_ini: String,
    pub filehighlight_ini: String,
    pub colortable_env: String,
    pub report: ExportReport,
}

pub fn export_mc(
    theme: &ResolvedTheme,
    roles: &SemanticRoles,
    palette: &Base16Palette,
    warnings: Vec<Warning>,
) -> McExport {
    let mut output = String::new();
    output.push_str("[skin]\n");
    output.push_str(&format!(
        "    description = {} - generated by Helix Theme Transformer\n",
        theme.name
    ));
    output.push_str("    truecolors = true\n");
    output.push('\n');
    output.push_str("[Lines]\n");
    for (key, value) in mc_lines() {
        output.push_str(&format!("    {key} = {value}\n"));
    }

    for section in mc_sections() {
        output.push('\n');
        output.push_str(&format!("[{}]\n", section.name));
        for entry in section.entries {
            output.push_str(&format!(
                "    {} = {}\n",
                entry.key,
                render_entry(&entry, roles, palette)
            ));
        }
    }

    let report = ExportReport {
        exporter: "mc".to_owned(),
        source: theme.source_path.to_string(),
        preserved: mc_preserved_items(roles),
        dropped: mc_dropped_items(theme),
        warnings,
    };
    McExport {
        skin_ini: output,
        filehighlight_ini: export_mc_filehighlight(),
        colortable_env: export_mc_colortable(roles, palette),
        report,
    }
}

pub fn export_mc_filehighlight() -> String {
    let mut output = String::new();
    output.push_str("[executable]\n    type=FILE_EXE\n\n");
    output.push_str("[directory]\n    type=DIR\n\n");
    output.push_str("[device]\n    type=DEVICE\n\n");
    output.push_str("[special]\n    type=SPECIAL\n\n");
    output.push_str("[stalelink]\n    type=STALE_LINK\n\n");
    output.push_str("[symlink]\n    type=SYMLINK\n\n");
    output.push_str("[core]\n    regexp=^core\\\\.*\\\\d*$\n    extensions_case=true\n\n");

    for group in mc_filehighlight_groups() {
        output.push_str(&format!("[{}]\n", group.section));
        output.push_str(&format!(
            "    extensions={}\n\n",
            group.extensions.join(";")
        ));
    }

    output.push_str(
        "# Hardlinks have lowest precedence to make them colored by file type or extension\n",
    );
    output.push_str("[hardlink]\n    type=HARDLINK\n");
    output
}

pub fn export_mc_colortable(roles: &SemanticRoles, palette: &Base16Palette) -> String {
    let mut output = String::new();
    output.push_str("# Generated by Helix Theme Transformer\n");
    output.push_str("export MC_COLOR_TABLE='");

    for (index, entry) in mc_colortable_entries().iter().enumerate() {
        if index > 0 {
            output.push(':');
        }
        output.push_str(entry.key);
        output.push('=');
        output.push_str(&resolve_colortable_color(entry.fg, roles, palette));
        output.push(',');
        output.push_str(&resolve_colortable_color(entry.bg, roles, palette));
        if !entry.attrs.is_empty() {
            output.push(',');
            output.push_str(&entry.attrs.join("+"));
        }
    }

    output.push_str("'\n");
    output
}

